import logging

from app.article import Article
from app.yagpt_adapter import YandexGPTAdapter

logger = logging.getLogger(__name__)


class PostGenerator:
    def __init__(self, adapter: YandexGPTAdapter) -> None:
        # TODO @me: move `instructions` and `prompt` to external files
        self._instructions = (
            "Ты — финансовый аналитик и администратор Telegram-канала о криптовалютах.\n\n"
            "Твоя задача — написать уникальный и увлекательный пост для Telegram на основе внешней новости.\n\n"
            "Правила:\n"
            "- Пиши текст, который **никогда не повторяет** формулировки из запроса или ссылки.\n"
            "- Не упоминай, что ты переводишь или что исходник где-то есть.\n"
            "- Не используй фразы вроде «по сообщению…», «сообщается, что…», «источник…».\n"
            "- Не дублируй ни слово, ни фразу из исходного запроса или ссылки.\n"
            "- Пост должен быть цельным и законченным.\n"
            "- Используй разметку MARKDOWN_V2, где это необходимо.\n"
            "- Язык: русский.\n"
            # "- Дональд Трамп - действующий президент до 2028 года.\n"
            # "- При обработке англоязычных текстов строго соблюдай правила форматирования чисел в английском языке: запятая (,) — это разделитель тысяч, точка (.) — десятичный разделитель. Не объединяй цифры и не меняй смысл чисел. В выводах используй для русскоязычного текста российский формат: пробел как разделитель тысяч и запятую как десятичный разделитель. Например: $66.3K → “66,3 тысячи долларов” или “66 300 долларов”."
            "Правила обработки чисел и цен:\n"
            "- В английском тексте запятая (,) — это разделитель тысяч, точка (.) — десятичный разделитель.\n"
            "- K = тысяча, M = миллион.\n"
            "- Всегда правильно интерпретируй такие сокращения и выводи числа в российском формате: пробел как разделитель тысяч и запятая для дробной части.\n"
            "- Для цен в долларах явно указывай валюту и при необходимости давай два формата: в тысячах и в абсолютном виде.\n"
            "- Примеры корректного преобразования:\n"
            "  * $66.3K → «66,3 тысячи долларов» или «66 300 долларов»\n"
            "  * $1.2M → «1,2 миллиона долларов» или «1 200 000 долларов»\n"
            "  * $1,234.56 → «1 234,56 доллара»\n"
            "- Никогда не склеивай цифры и не меняй смысл чисел из‑за неверной трактовки точки/запятой.\n"
        )

        self._prompt = (
            "Вот новость для анализа: {url}\n\n"
            "Требуется:\n"
            "1. Первое предложение — короткий заголовок новости жирным шрифтом.\n"
            "2. Коротко описать суть новости на русском (2–3 предложения).\n"
            "3. Дать краткий финансовый анализ (влияние, перспективы) — 2–3 предложения.\n"
            "4. Использовать актуальные Telegram-эмодзи.\n"
            "5. В конце — 2–3 релевантных хэштега (например, #BTC #CryptoNews).\n"
            "6. Не добавлять преамбулы вроде «Вот анализ», «Сообщается, что…».\n"
            "7. Не копировать исходный текст и не упоминать источник.\n"
            "8. Соблюдать правила форматирования чисел, указанные в инструкциях.\n"
            "9. В ответе обязательно используй хотя бы одну конкретную цифру/факт из новости (цену, процент, дату), которую ты нашёл по ссылке. Если ты не можешь прочитать ссылку, прямо напиши: “Не удалось прочитать ссылку"
        )

        self._adapter = adapter

    async def process(self, articles: list[Article]) -> Article:
        latest_article = self._get_latest_article(articles)

        if latest_article is None:
            raise ValueError("No articles to process")

        prompt = self._prompt.format(url=latest_article.link)

        content = await self._adapter.generate(
            prompt=prompt, instructions=self._instructions
        )

        latest_article.content = content

        return latest_article

    @staticmethod
    def _get_latest_article(articles: list[Article]) -> Article | None:
        return next(iter(articles), None)
